-- TicketFlow initial schema
-- Cross-module references (created_by_id, assigned_to_id, changed_by_id, author_id)
-- are plain ids in the domain; integrity is enforced here with foreign keys.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active      BOOLEAN       NOT NULL,
    created_at  TIMESTAMP(6)  NOT NULL,
    email       VARCHAR(255)  NOT NULL UNIQUE,
    full_name   VARCHAR(255)  NOT NULL,
    password    VARCHAR(255)  NOT NULL,
    role        VARCHAR(255)  NOT NULL,
    username    VARCHAR(255)  NOT NULL UNIQUE
);

CREATE TABLE tickets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assigned_to_id  BIGINT,
    category        VARCHAR(255),
    closed_at       TIMESTAMP(6),
    created_at      TIMESTAMP(6)  NOT NULL,
    created_by_id   BIGINT        NOT NULL,
    description     VARCHAR(2000),
    priority        VARCHAR(255)  NOT NULL,
    resolved_at     TIMESTAMP(6),
    sla_breached    BOOLEAN       NOT NULL,
    sla_deadline    TIMESTAMP(6)  NOT NULL,
    status          VARCHAR(255)  NOT NULL,
    title           VARCHAR(255)  NOT NULL,
    updated_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_tickets_created_by  FOREIGN KEY (created_by_id)  REFERENCES users(id),
    CONSTRAINT fk_tickets_assigned_to FOREIGN KEY (assigned_to_id) REFERENCES users(id)
);

CREATE TABLE ticket_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at    TIMESTAMP(6)  NOT NULL,
    changed_by_id BIGINT        NOT NULL,
    field         VARCHAR(255)  NOT NULL,
    new_value     VARCHAR(255),
    old_value     VARCHAR(255),
    ticket_id     BIGINT        NOT NULL,
    CONSTRAINT fk_history_ticket     FOREIGN KEY (ticket_id)     REFERENCES tickets(id),
    CONSTRAINT fk_history_changed_by FOREIGN KEY (changed_by_id) REFERENCES users(id)
);

CREATE TABLE ticket_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id   BIGINT        NOT NULL,
    created_at  TIMESTAMP(6)  NOT NULL,
    internal    BOOLEAN       NOT NULL,
    message     VARCHAR(2000) NOT NULL,
    ticket_id   BIGINT        NOT NULL,
    CONSTRAINT fk_comments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id),
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users(id)
);

-- Used by the SLA scheduler (runs every minute) and agent workload counts
CREATE INDEX idx_tickets_status_sla_deadline ON tickets (status, sla_deadline);
CREATE INDEX idx_tickets_assigned_to ON tickets (assigned_to_id);
CREATE INDEX idx_history_ticket ON ticket_history (ticket_id);
CREATE INDEX idx_comments_ticket ON ticket_comments (ticket_id);
